CREATE TABLE faculdade (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    endereco VARCHAR(255),
    nome VARCHAR(255),
    telefone VARCHAR(255)
);

CREATE TABLE onibus (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    capacidade INTEGER,
    foto_url TEXT,
    modelo VARCHAR(255),
    numero_identificacao VARCHAR(255),
    placa VARCHAR(255),
    status_onibus VARCHAR(255),
    CONSTRAINT onibus_status_onibus_check
        CHECK (status_onibus IN ('OPERANDO', 'MANUTENCAO', 'QUEBRADO', 'INATIVO'))
);

CREATE TABLE pessoa (
    dtype VARCHAR(31) NOT NULL,
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cpf_cnpj VARCHAR(255),
    nome VARCHAR(255),
    telefone VARCHAR(255),
    tipo_pessoa VARCHAR(255),
    data_cadastro DATE,
    matricula VARCHAR(255),
    mensalidade NUMERIC(38,2),
    status_matricula VARCHAR(255),
    cnh VARCHAR(255),
    salario NUMERIC(38,2),
    faculdade_id BIGINT,
    CONSTRAINT pessoa_dtype_check CHECK (dtype IN ('Pessoa', 'Aluno', 'Motorista')),
    CONSTRAINT pessoa_status_matricula_check CHECK (status_matricula IN ('ATIV0', 'INATIV0', 'PENDENTE')),
    CONSTRAINT pessoa_tipo_pessoa_check CHECK (tipo_pessoa IN ('ADMIN', 'ALUNO', 'MOTORISTA')),
    CONSTRAINT fk_pessoa_faculdade FOREIGN KEY (faculdade_id) REFERENCES faculdade(id)
);

CREATE TABLE usuario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255),
    senha VARCHAR(255),
    tipo_pessoa VARCHAR(255),
    CONSTRAINT usuario_tipo_pessoa_check CHECK (tipo_pessoa IN ('ADMIN', 'ALUNO', 'MOTORISTA'))
);

CREATE TABLE rota (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descricao VARCHAR(255),
    nome VARCHAR(255),
    faculdade_id BIGINT,
    CONSTRAINT fk_rota_faculdade FOREIGN KEY (faculdade_id) REFERENCES faculdade(id)
);

CREATE TABLE ponto_embarque (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descricao VARCHAR(255),
    ordem_parada INTEGER,
    rota_id BIGINT,
    CONSTRAINT fk_ponto_embarque_rota FOREIGN KEY (rota_id) REFERENCES rota(id)
);

CREATE TABLE rota_pontos_embarque (
    rota_id BIGINT NOT NULL,
    pontos_embarque_id BIGINT NOT NULL,
    CONSTRAINT fk_rota_pontos_rota FOREIGN KEY (rota_id) REFERENCES rota(id),
    CONSTRAINT fk_rota_pontos_ponto FOREIGN KEY (pontos_embarque_id) REFERENCES ponto_embarque(id)
);

CREATE TABLE grade_diaria (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descricao VARCHAR(255),
    dia_semana VARCHAR(255),
    CONSTRAINT grade_diaria_dia_semana_check
        CHECK (dia_semana IN ('SEGUNDA', 'TERCA', 'QUARTA', 'QUINTA', 'SEXTA'))
);

CREATE TABLE viagem (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data DATE,
    grade_diaria_id BIGINT,
    motorista_id BIGINT,
    onibus_id BIGINT,
    rota_id BIGINT,
    CONSTRAINT fk_viagem_grade FOREIGN KEY (grade_diaria_id) REFERENCES grade_diaria(id),
    CONSTRAINT fk_viagem_motorista FOREIGN KEY (motorista_id) REFERENCES pessoa(id),
    CONSTRAINT fk_viagem_onibus FOREIGN KEY (onibus_id) REFERENCES onibus(id),
    CONSTRAINT fk_viagem_rota FOREIGN KEY (rota_id) REFERENCES rota(id)
);

CREATE TABLE viagem_faculdade (
    viagem_id BIGINT NOT NULL,
    faculdade_id BIGINT NOT NULL,
    CONSTRAINT fk_viagem_faculdade_viagem FOREIGN KEY (viagem_id) REFERENCES viagem(id),
    CONSTRAINT fk_viagem_faculdade_faculdade FOREIGN KEY (faculdade_id) REFERENCES faculdade(id)
);

CREATE TABLE conta_pagar (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_vencimento DATE,
    descricao VARCHAR(255),
    status VARCHAR(255),
    valor NUMERIC(38,2),
    pessoa_id BIGINT,
    CONSTRAINT conta_pagar_status_check CHECK (status IN ('PENDENTE', 'PAGO', 'ATRASADO')),
    CONSTRAINT fk_conta_pagar_pessoa FOREIGN KEY (pessoa_id) REFERENCES pessoa(id)
);

CREATE TABLE pagamento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_pagamento DATE,
    forma_pagamento VARCHAR(255),
    valor NUMERIC(38,2),
    conta_pagar_id BIGINT,
    CONSTRAINT pagamento_forma_pagamento_check
        CHECK (forma_pagamento IN ('PIX', 'DINHEIRO', 'CARTAO', 'BOLETO', 'TRANSFERENCIA')),
    CONSTRAINT fk_pagamento_conta FOREIGN KEY (conta_pagar_id) REFERENCES conta_pagar(id)
);

CREATE TABLE conta_receber (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_vencimento DATE,
    descricao VARCHAR(255),
    status VARCHAR(255),
    valor NUMERIC(38,2),
    aluno_id BIGINT,
    CONSTRAINT conta_receber_status_check CHECK (status IN ('PENDENTE', 'PAGO', 'ATRASADO')),
    CONSTRAINT fk_conta_receber_aluno FOREIGN KEY (aluno_id) REFERENCES pessoa(id)
);

CREATE TABLE recebimento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_recebimento DATE,
    forma_pagamento VARCHAR(255),
    valor NUMERIC(38,2),
    conta_receber_id BIGINT,
    CONSTRAINT recebimento_forma_pagamento_check
        CHECK (forma_pagamento IN ('PIX', 'DINHEIRO', 'CARTAO', 'BOLETO', 'TRANSFERENCIA')),
    CONSTRAINT fk_recebimento_conta FOREIGN KEY (conta_receber_id) REFERENCES conta_receber(id)
);

CREATE TABLE chamado_manutencao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_abertura DATE,
    descricao VARCHAR(255),
    status VARCHAR(255),
    urgencia VARCHAR(255),
    onibus_id BIGINT,
    responsavel_id BIGINT,
    CONSTRAINT chamado_manutencao_status_check CHECK (status IN ('ABERTO', 'EM_ANDAMENTO', 'RESOLVIDO')),
    CONSTRAINT chamado_manutencao_urgencia_check CHECK (urgencia IN ('BAIXA', 'MEDIA', 'ALTA')),
    CONSTRAINT fk_chamado_onibus FOREIGN KEY (onibus_id) REFERENCES onibus(id),
    CONSTRAINT fk_chamado_responsavel FOREIGN KEY (responsavel_id) REFERENCES pessoa(id)
);
