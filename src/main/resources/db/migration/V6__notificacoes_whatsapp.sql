CREATE TABLE whatsapp_configuracao (
    id BIGINT PRIMARY KEY CHECK (id = 1),
    automatico BOOLEAN NOT NULL DEFAULT FALSE,
    ultima_reserva TIMESTAMP WITH TIME ZONE,
    webhook_verificado_em TIMESTAMP WITH TIME ZONE,
    webhook_fingerprint VARCHAR(255),
    template_verificado_em TIMESTAMP WITH TIME ZONE,
    template_fingerprint VARCHAR(255)
);
INSERT INTO whatsapp_configuracao(id, automatico) VALUES (1, FALSE);

CREATE TABLE whatsapp_assinatura (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL UNIQUE REFERENCES usuario(id) ON DELETE CASCADE,
    numero VARCHAR(16) NOT NULL,
    status VARCHAR(16) NOT NULL CHECK (status IN ('PENDENTE','ATIVA','CANCELADA')),
    consentimento_em TIMESTAMP WITH TIME ZONE NOT NULL,
    confirmado_em TIMESTAMP WITH TIME ZONE,
    cancelado_em TIMESTAMP WITH TIME ZONE,
    codigo_hash VARCHAR(64),
    codigo_expira_em TIMESTAMP WITH TIME ZONE,
    janela_ativacoes TIMESTAMP WITH TIME ZONE NOT NULL,
    ativacoes_na_janela INTEGER NOT NULL,
    revisao BIGINT NOT NULL,
    ultimo_cancelamento_mensagem_id VARCHAR(255)
);
CREATE UNIQUE INDEX uk_whatsapp_numero_ativo ON whatsapp_assinatura(numero) WHERE status = 'ATIVA';
CREATE UNIQUE INDEX uk_whatsapp_codigo ON whatsapp_assinatura(codigo_hash) WHERE codigo_hash IS NOT NULL;

CREATE TABLE whatsapp_lote (
    id UUID PRIMARY KEY,
    data_referencia DATE NOT NULL,
    dia_automatico DATE UNIQUE,
    origem VARCHAR(16) NOT NULL CHECK (origem IN ('MANUAL','AUTOMATICA')),
    publico VARCHAR(16) NOT NULL CHECK (publico IN ('TODOS','ALUNOS','MOTORISTAS')),
    reenvio BOOLEAN NOT NULL,
    motivo VARCHAR(500),
    criado_em TIMESTAMP WITH TIME ZONE NOT NULL,
    solicitante_id BIGINT REFERENCES usuario(id) ON DELETE SET NULL,
    ignorados_duplicidade INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE whatsapp_entrega (
    id UUID PRIMARY KEY,
    lote_id UUID NOT NULL REFERENCES whatsapp_lote(id),
    usuario_id BIGINT REFERENCES usuario(id) ON DELETE SET NULL,
    destinatario_original_id BIGINT NOT NULL,
    nome_destinatario VARCHAR(255) NOT NULL,
    numero VARCHAR(16) NOT NULL,
    data_referencia DATE NOT NULL,
    revisao INTEGER NOT NULL,
    assinatura_revisao BIGINT NOT NULL,
    referencia VARCHAR(1000) NOT NULL,
    programacao_json TEXT,
    pdf BYTEA,
    status VARCHAR(16) NOT NULL CHECK (status IN ('PENDENTE','PROCESSANDO','ACEITA','ENVIADA','ENTREGUE','LIDA','FALHA','INCERTA','SUPRIMIDA','EXPIRADA')),
    tentativas INTEGER NOT NULL DEFAULT 0,
    criado_em TIMESTAMP WITH TIME ZONE NOT NULL,
    atualizado_em TIMESTAMP WITH TIME ZONE,
    proxima_tentativa TIMESTAMP WITH TIME ZONE,
    processamento_em TIMESTAMP WITH TIME ZONE,
    reserva UUID,
    mensagem_meta_id VARCHAR(255) UNIQUE,
    erro VARCHAR(255),
    CONSTRAINT uk_whatsapp_entrega_diaria UNIQUE(data_referencia, destinatario_original_id, revisao)
);
CREATE INDEX ix_whatsapp_fila ON whatsapp_entrega(status, proxima_tentativa, criado_em);
CREATE INDEX ix_whatsapp_lote_entrega ON whatsapp_entrega(lote_id);
